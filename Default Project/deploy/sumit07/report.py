"""Build a self-contained HTML dashboard from charts and insights."""

from __future__ import annotations

import base64
import html as html_lib
from datetime import datetime
from typing import Iterable, Optional

from .store import Chart

_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>{title}</title>
<style>
  :root {{ color-scheme: light; }}
  * {{ box-sizing: border-box; }}
  body {{
    margin: 0; padding: 32px;
    font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
    background: #f5f7fb; color: #1f2937;
  }}
  header {{ margin-bottom: 24px; }}
  header h1 {{ margin: 0 0 4px; font-size: 28px; }}
  header .meta {{ color: #6b7280; font-size: 13px; }}
  .insights {{
    background: #fff; border: 1px solid #e5e7eb; border-radius: 14px;
    padding: 20px 24px; margin-bottom: 24px;
  }}
  .insights h2 {{ margin-top: 0; font-size: 18px; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(420px, 1fr)); gap: 20px; }}
  .card {{
    background: #fff; border: 1px solid #e5e7eb; border-radius: 14px;
    padding: 16px; box-shadow: 0 1px 2px rgba(16,24,40,.05);
  }}
  .card h3 {{ margin: 0 0 10px; font-size: 15px; color: #374151; }}
  .card img {{ width: 100%; height: auto; border-radius: 8px; display: block; }}
  footer {{ margin-top: 28px; color: #9ca3af; font-size: 12px; text-align: center; }}
</style>
</head>
<body>
  <header>
    <h1>{title}</h1>
    <div class="meta">Generated by Sumit07 · {timestamp}</div>
  </header>
  {insights}
  <div class="grid">
  {cards}
  </div>
  <footer>Sumit07 — your autonomous data analyst.</footer>
</body>
</html>
"""


def _escape_multiline(text: str) -> str:
    escaped = html_lib.escape(text.strip())
    return escaped.replace("\n", "<br/>")


def build_dashboard_html(
    title: str,
    charts: Iterable[Chart],
    insights: Optional[str] = None,
) -> str:
    """Return a standalone HTML dashboard embedding the given charts."""
    cards = []
    for chart in charts:
        b64 = base64.b64encode(chart.png).decode("ascii")
        cards.append(
            '<div class="card">'
            f"<h3>{html_lib.escape(chart.title)}</h3>"
            f'<img alt="{html_lib.escape(chart.title)}" src="data:image/png;base64,{b64}"/>'
            "</div>"
        )

    insights_html = ""
    if insights and insights.strip():
        insights_html = (
            '<section class="insights"><h2>Key insights</h2>'
            f"<p>{_escape_multiline(insights)}</p></section>"
        )

    return _TEMPLATE.format(
        title=html_lib.escape(title or "Sumit07 Dashboard"),
        timestamp=datetime.now().strftime("%Y-%m-%d %H:%M"),
        insights=insights_html,
        cards="\n".join(cards) if cards else "<p>No charts were included.</p>",
    )
